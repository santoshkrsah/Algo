def login_url():
    return f"https://{HOST}/?appcode={C.get('API_KEY', '')}"


def checksum(user_id, auth_code, secret):
    return hashlib.sha256((user_id + auth_code + secret).encode("utf-8")).hexdigest()


def parse_redirect(text):
    """(authCode, userId or None) from the redirect address (or from a bare authCode)."""
    text = text.strip().strip('"').strip("'")
    if "authCode=" in text or "authcode=" in text.lower():
        q = urllib.parse.parse_qs(urllib.parse.urlsplit(text).query)
        q = {k.lower(): v[0] for k, v in q.items()}
        return q.get("authcode", "").strip(), (q.get("userid") or None)
    return text, None


def get_session(auth_code, user_id=None):
    """Log in with an authCode. Returns {"userSession", "clientId", "userId", "day"} or raises RuntimeError with the reason."""
    user_id = user_id or C.get("USERID", "")
    if not (user_id and auth_code and C.get("API_SECRET")):
        raise RuntimeError("USERID / authCode / API_SECRET missing")
    st, r = https("POST", HOST, BASE + "/vendor/getUserDetails", {"checkSum": checksum(user_id, auth_code, C["API_SECRET"])},
                  {"Content-Type": "application/json", "Accept": "application/json"})
    if not isinstance(r, dict) or r.get("stat") != "Ok" or not r.get("userSession"):
        raise RuntimeError(f"login refused (HTTP {st}): {str(r)[:200]}")
    sess = {"userSession": r["userSession"], "clientId": r.get("clientId"), "userId": user_id,
            "day": datetime.now(IST).strftime("%Y-%m-%d"), "saved": datetime.now(IST).isoformat()}
    save_session(sess)
    return sess


def session_path(day=None):
    return os.path.join(HERE, f"BeyondTrading_session_{day or datetime.now(IST).strftime('%Y-%m-%d')}.json")


def save_session(sess):
    json.dump(sess, open(session_path(sess["day"]), "w", encoding="utf-8"))


def load_session():
    p = session_path()
    if os.path.exists(p):
        try:
            return json.load(open(p, encoding="utf-8"))
        except Exception:
            return None
    return None


def clear_session():
    try:
        os.remove(session_path())
    except OSError:
        pass


class SessionExpired(Exception):
    pass


class API:
    """Authenticated calls. call() returns the parsed JSON (dict / list) or None when there was no usable reply."""

    def __init__(self, session):
        self.s = session

    def call(self, method, path, body=None):
        h = {"Content-Type": "application/json", "Accept": "application/json",
             "Authorization": "Bearer " + self.s["userSession"]}
        try:
            st, r = https(method, HOST, BASE + path, body, h)
        except Exception as e:
            say(f"[{path}] network error: {str(e)[:150]}")
            return None
        if st == 401 or (isinstance(r, dict) and re.search(r"session expired|EC087", json.dumps(r), re.I)):
            raise SessionExpired(f"{path}: HTTP {st} {str(r)[:120]}")
        if not isinstance(r, (dict, list)):
            return {"status": "Not_ok", "message": f"HTTP {st}", "raw": str(r)[:200]}
        return r

    @staticmethod
    def ok(r):
        return isinstance(r, dict) and str(r.get("status", r.get("stat", ""))).lower() == "ok"


