def say(msg):
    print(msg, flush=True)


def read_credentials(path=CRED_FILE):
    out = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            out["_".join(k.upper().split())] = v.strip()
    return out


C = read_credentials() if os.path.exists(CRED_FILE) else {}

_ctx = None


def ssl_context():
    global _ctx
    if _ctx is None:
        _ctx = ssl.create_default_context()
        try:
            _ctx.load_verify_locations(cadata=EXTRA_ROOTS)
        except (ssl.SSLError, ValueError) as e:
            say(f"[ssl] extra root certificates not loaded: {e}")
    return _ctx


